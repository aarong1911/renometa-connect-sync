-- No authenticated INSERT/UPDATE/DELETE policy — rows are written only by
-- log_estimate_activity() (SECURITY DEFINER, below) or service-role
-- Netlify functions, both of which bypass RLS by design.

create or replace function public.log_estimate_activity()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid;
begin
  v_actor := auth.uid();

  if tg_op = 'INSERT' then
    insert into public.estimate_activities (org_id, estimate_id, version_number, activity_type, actor_id, actor_type, title)
    values (new.org_id, new.id, new.version_number, 'created', v_actor, case when v_actor is null then 'system' else 'user' end, 'Estimate created');
    return new;
  end if;

  if old.status is distinct from new.status then
    case new.status
      when 'ready' then
        insert into public.estimate_activities (org_id, estimate_id, version_number, activity_type, actor_id, actor_type, title)
        values (new.org_id, new.id, new.version_number, 'marked_ready', v_actor, case when v_actor is null then 'system' else 'user' end, 'Marked ready');
      when 'cancelled' then
        insert into public.estimate_activities (org_id, estimate_id, version_number, activity_type, actor_id, actor_type, title)
        values (new.org_id, new.id, new.version_number, 'cancelled', v_actor, case when v_actor is null then 'system' else 'user' end, 'Estimate cancelled');
      when 'archived' then
        insert into public.estimate_activities (org_id, estimate_id, version_number, activity_type, actor_id, actor_type, title)
        values (new.org_id, new.id, new.version_number, 'archived', v_actor, case when v_actor is null then 'system' else 'user' end, 'Estimate archived');
      when 'draft' then
        if old.status in ('cancelled', 'rejected', 'expired') then
          insert into public.estimate_activities (org_id, estimate_id, version_number, activity_type, actor_id, actor_type, title)
          values (new.org_id, new.id, new.version_number, 'restored', v_actor, case when v_actor is null then 'system' else 'user' end, 'Estimate restored to draft');
        end if;
      else null; -- sent/viewed/approved/rejected/changes_requested/expired/converted are written explicitly by the app-layer/proposal functions that own those transitions (they carry customer-facing context a generic trigger can't produce honestly)
    end case;
  end if;

  return new;
end;
$$;

revoke all on function public.log_estimate_activity() from public;

comment on function public.log_estimate_activity() is
  'Phase 10.4 — AFTER INSERT/UPDATE ON estimates. Owns only the internal-user-driven transitions (created/marked_ready/cancelled/archived/restored); sent/viewed/approved/rejected/changes_requested/expired/converted are written explicitly by their owning code path (estimate-send.ts, proposal-action.ts, the conversion actions) since those need customer-facing context this generic trigger cannot honestly produce.';

drop trigger if exists estimates_log_activity on public.estimates;
create trigger estimates_log_activity
  after insert or update on public.estimates
  for each row
  execute function public.log_estimate_activity();

