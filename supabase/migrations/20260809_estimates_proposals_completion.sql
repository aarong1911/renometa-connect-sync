create or replace function public.set_estimate_number()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_next bigint;
begin
  if new.number is not null then
    return new;
  end if;

  -- Per-organization sequential counter derived transactionally from the
  -- org's own current max — guarded with an advisory lock on org_id so two
  -- concurrent inserts for the same org can never compute the same next
  -- number (a bare "select max(...)+1" alone is not concurrency-safe).
  perform pg_advisory_xact_lock(hashtext('estimate_number:' || new.org_id::text));

  select coalesce(max(substring(number from 'EST-(\d+)')::bigint), 0) + 1
    into v_next
    from public.estimates
    where org_id = new.org_id and number ~ '^EST-\d+$';

  new.number := 'EST-' || lpad(v_next::text, 6, '0');
  return new;
end;
$$;

comment on function public.set_estimate_number() is
  'Phase 10.4 — assigns estimates.number (EST-000001 format) server-side on INSERT when not already set. Org-scoped, advisory-lock-guarded for concurrency safety. Immutable thereafter (no UPDATE trigger).';

drop trigger if exists estimates_set_number on public.estimates;
create trigger estimates_set_number
  before insert on public.estimates
  for each row
  execute function public.set_estimate_number();

