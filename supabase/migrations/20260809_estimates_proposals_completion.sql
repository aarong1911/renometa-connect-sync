-- ── same-org validation triggers (mirror validate_project_owner/_lead) ───
create or replace function public.validate_estimate_relationships()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.org_id is null then
    raise exception 'estimates.org_id is required';
  end if;

  if new.owner_id is not null and not exists (
    select 1 from public.org_memberships where member_id = new.owner_id and org_id = new.org_id
    union
    select 1 from public.profiles where id = new.owner_id and organization_id = new.org_id
  ) then
    raise exception 'Estimate owner is not a member of this organization';
  end if;

  if new.company_id is not null and not exists (
    select 1 from public.companies where id = new.company_id and org_id = new.org_id
  ) then
    raise exception 'Linked account not found in this organization';
  end if;

  if new.lead_id is not null and not exists (
    select 1 from public.leads where id = new.lead_id and org_id = new.org_id
  ) then
    raise exception 'Linked lead not found in this organization';
  end if;

  return new;
end;
$$;

comment on function public.validate_estimate_relationships() is
  'Enforces that estimates.owner_id/company_id/lead_id all belong to estimates.org_id. SECURITY INVOKER: relies on the acting user''s own RLS-scoped read access (client_id/deal_id/project_id already have real FKs with their own referential integrity).';

drop trigger if exists estimates_validate_relationships on public.estimates;
create trigger estimates_validate_relationships
  before insert or update of owner_id, company_id, lead_id, org_id on public.estimates
  for each row
  execute function public.validate_estimate_relationships();

